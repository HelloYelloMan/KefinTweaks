#!/usr/bin/env node
// Translates the mpv CRT chain to GLSL ES for the CRT Shader feature.
//
//   tools/build-crt-shaders.mjs            every profile in retro.conf
//   tools/build-crt-shaders.mjs retro-super
//
// WHY. The mpv shaders are desktop GLSL: libplacebo compiles them with
// glslang, which allows implicit int->float conversion, scalar swizzles and
// non-constant global initializers. WebGL2 accepts only GLSL ES 3.00, which
// allows none of those, and fixing 28k lines of machine-converted slang by
// hand would fork them from mpv. So this does what libplacebo does -- glslang,
// desktop semantics, to SPIR-V -- and then SPIRV-Cross writes that back out as
// GLSL ES. The result is the same program, typed exactly as mpv compiles it,
// and only the code each pass actually reaches.
//
// HOW IT STAYS IN STEP. Each pass is generated by scripts/crtShader.js itself
// (loaded here in a sandbox), so the uniforms, macros and bindings are the
// runtime's own. The output is keyed by a hash of the GLSL ES source the
// runtime would generate for that pass: if the mpv files or retro.conf change
// and this is not re-run, the hashes stop matching and the runtime says the
// build is stale instead of running old code.
//
// Needs glslangValidator (package glslang) and spirv-cross; set SPIRV_CROSS if
// it is not at ~/dev/SPIRV-Cross/build/spirv-cross.
import vm from 'node:vm';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir, homedir } from 'node:os';
import path from 'node:path';

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SPIRV_CROSS = process.env.SPIRV_CROSS || path.join(homedir(), 'dev/SPIRV-Cross/build/spirv-cross');
const OUT_DIR = path.join(REPO, 'scripts/crt/build');
if (!existsSync(SPIRV_CROSS)) { console.error(`spirv-cross not found at ${SPIRV_CROSS}`); process.exit(1); }

// Load the runtime in a sandbox with just enough of a browser for it.
const window = { KefinTweaksConfig: { kefinTweaksRoot: '/' } };
const sandbox = {
    window, performance, setTimeout: () => 0,
    console: { log() {}, warn: (...a) => console.warn('  warn:', ...a), error: console.error },
    localStorage: { getItem: () => null, setItem() {} },
    HTMLVideoElement: Object.assign(function () {}, { prototype: {} }),
    fetch: async (url) => ({ ok: true, text: async () => readFileSync(path.join(REPO, url), 'utf8') })
};
vm.createContext(sandbox);
vm.runInContext(readFileSync(path.join(REPO, 'scripts/crtShader.js'), 'utf8'), sandbox);
const crt = window.KefinTweaksCrt;

const conf = readFileSync(path.join(REPO, 'scripts/crt/retro.conf.txt'), 'utf8');
const parsed = crt._parseRetroConf(conf);
const profiles = process.argv.slice(2).length ? process.argv.slice(2)
    : Object.keys(parsed).filter((p) => parsed[p].shaders && parsed[p].shaders.length);

const work = mkdtempSync(path.join(tmpdir(), 'crt-build-'));
try {
    for (const profile of profiles) {
        const { passes } = await crt._loadMpvProfile(profile, 'desktop');
        const out = { format: 1, profile, generated: new Date().toISOString(), passes: {} };
        let bytes = 0;
        for (const [i, pass] of passes.entries()) {
            const src = path.join(work, `p${i}.frag`);
            const spv = path.join(work, `p${i}.spv`);
            const es = path.join(work, `p${i}.es.frag`);
            writeFileSync(src, pass.source);
            try {
                execFileSync('glslangValidator', ['-G', '--auto-map-locations', '--auto-map-bindings', '-S', 'frag', '-o', spv, src], { stdio: 'pipe' });
            } catch (e) {
                console.error(`${profile}: ${pass.file}: ${pass.desc}: glslang failed\n${e.stdout}`);
                process.exit(1);
            }
            execFileSync(SPIRV_CROSS, [spv, '--es', '--version', '300', '--output', es], { stdio: 'pipe' });
            // SPIRV-Cross defaults ES fragment floats to mediump; this chain
            // needs every bit of highp (linear light, bloom above 1.0).
            const text = readFileSync(es, 'utf8')
                .replace(/precision mediump float;/g, 'precision highp float;')
                .replace(/precision mediump int;/g, 'precision highp int;');
            out.passes[crt._sourceKey(pass.esSource)] = text;
            bytes += text.length;
            console.log(`  ${profile} ${String(i).padStart(2)}  ${(text.length / 1024).toFixed(0).padStart(5)} KB  ${pass.file}: ${pass.desc}`);
        }
        const file = path.join(OUT_DIR, `${profile}.json`);
        writeFileSync(file, JSON.stringify(out));
        console.log(`${profile}: ${passes.length} passes, ${(bytes / 1024).toFixed(0)} KB -> ${path.relative(REPO, file)}`);
    }
} finally {
    rmSync(work, { recursive: true, force: true });
}
